using System;
using System.Linq;
using dnlib.DotNet;
using dnlib.DotNet.Emit;
using dnlib.DotNet.Writer;

if (args.Length != 2) throw new ArgumentException("input managed, output managed");
using var module = ModuleDefMD.Load(args[0]);
var helperAssembly = module.GetAssemblyRefs().Single(a => a.Name == "SoulFlowerHeroArt");
var helper = new TypeRefUser(module, "HYJS.HeroArt", "HeroArtFallback", helperAssembly);
var texture = module.GetTypes().Single(t => t.FullName == "UITexture");
var iterator = module.GetTypes().Single(t => t.Name == "<_SetTextureAsync>c__Iterator2A" && t.DeclaringType.FullName == "AssetLoadHelper");
var method = iterator.Methods.Single(m => m.Name == "MoveNext");
var body = method.Body;
var setters = body.Instructions.Where(i => i.OpCode == OpCodes.Callvirt && i.Operand is IMethod m && m.DeclaringType.FullName == "UITexture" && m.Name == "set_mainTexture").ToArray();
var pixels = body.Instructions.Where(i => i.OpCode == OpCodes.Callvirt && i.Operand is IMethod m && m.DeclaringType.FullName == "UITexture" && m.Name == "MakePixelPerfect").ToArray();
if (setters.Length != 1 || pixels.Length != 1) throw new InvalidOperationException("Original async texture method differs");
var assetType = ((IMethod)setters[0].Operand).MethodSig.Params[0];
var assign = new MemberRefUser(module, "AssignRequested", MethodSig.CreateStatic(module.CorLibTypes.Void, texture.ToTypeSig(), assetType, module.CorLibTypes.String), helper);
var pixel = new MemberRefUser(module, "MakeRequestedPixelPerfect", MethodSig.CreateStatic(module.CorLibTypes.Void, texture.ToTypeSig()), helper);
var setter = setters[0];
var index = body.Instructions.IndexOf(setter);
body.Instructions.Insert(index++, Instruction.Create(OpCodes.Ldarg_0));
body.Instructions.Insert(index, Instruction.Create(OpCodes.Ldfld, iterator.Fields.Single(f => f.Name == "bundleName")));
setter.OpCode = OpCodes.Call;
setter.Operand = assign;
pixels[0].OpCode = OpCodes.Call;
pixels[0].Operand = pixel;
body.MaxStack = Math.Max(body.MaxStack, (ushort)4);
body.KeepOldMaxStack = true;
body.SimplifyBranches();
body.OptimizeBranches();
var options = new ModuleWriterOptions(module);
options.MetadataOptions.Flags |= MetadataFlags.PreserveAll | MetadataFlags.KeepOldMaxStack;
module.Write(args[1], options);
Console.WriteLine("One original AssetLoadHelper texture coroutine extended with request-scoped crop and original-size guard");
