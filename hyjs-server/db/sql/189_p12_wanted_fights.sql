-- P12独立Wanted域；本地规则与原表快照由InitializeP12Wanted冻结，默认关闭待完整资格。
CREATE TABLE IF NOT EXISTS `p12_wanted_fights` (
  `id` VARCHAR(64) NOT NULL,
  `player_id` BIGINT NOT NULL,
  `instance_id` VARCHAR(64) NOT NULL,
  `stamp` BIGINT NOT NULL,
  `attack_type` BIGINT NOT NULL,
  `cost` BIGINT NOT NULL,
  `created_at` BIGINT NOT NULL,
  `committed` BOOLEAN NOT NULL,
  `committed_at` BIGINT NOT NULL,
  `abandoned_at` BIGINT NOT NULL,
  `input_json` LONGTEXT NOT NULL,
  `input_hash` VARCHAR(64) NOT NULL,
  `start_proto` LONGBLOB NOT NULL,
  `start_hash` VARCHAR(64) NOT NULL,
  `terminal_json` LONGTEXT NOT NULL,
  `terminal_hash` VARCHAR(64) NOT NULL,
  `end_proto` LONGBLOB NOT NULL,
  `end_hash` VARCHAR(64) NOT NULL,
  `end_request_hash` VARCHAR(64) NOT NULL,
  `applied_damage` DOUBLE NOT NULL,
  `performance` BIGINT NOT NULL,
  `score` BIGINT NOT NULL,
  PRIMARY KEY (`id`),
  KEY `idx_p12_wanted_pending` (`player_id`,`committed`),
  KEY `idx_p12_wanted_fights_instance_id` (`instance_id`),
  KEY `idx_p12_wanted_fights_stamp` (`stamp`),
  KEY `idx_p12_wanted_fights_committed_at` (`committed_at`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
