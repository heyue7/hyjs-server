CREATE TABLE IF NOT EXISTS `p13_union_fight_player_recoveries` (
 `pending_id` CHAR(64) NOT NULL DEFAULT '',
 `id` CHAR(64) NOT NULL,
 `match_id` CHAR(64) NOT NULL,
 `player_id` BIGINT NOT NULL,
 `kind` VARCHAR(8) NOT NULL,
 `item_id` VARCHAR(32) NOT NULL,
 `stamp` BIGINT NOT NULL DEFAULT 0,
 `nonce` VARCHAR(32) NOT NULL DEFAULT '',
 `caster_id` BIGINT NOT NULL,
 `effect_guid` BIGINT NOT NULL DEFAULT 0,
 `offer_hash` CHAR(64) NOT NULL,
 `hp_percent` BIGINT NOT NULL,
 `inventory_before` INT NOT NULL DEFAULT 0,
 `inventory_after` INT NOT NULL DEFAULT 0,
 `dead_ordinal` BIGINT NOT NULL,
 `logical_at` BIGINT NOT NULL,
 `applied_at` BIGINT NOT NULL,
 `before` BLOB NOT NULL,
 `after` BLOB NOT NULL,
 `before_hash` CHAR(64) NOT NULL,
 `after_hash` CHAR(64) NOT NULL,
 `source_hash` CHAR(64) NOT NULL,
 PRIMARY KEY (`id`),
 KEY `p13_recovery_order` (`match_id`,`player_id`,`logical_at`),
 KEY `p13_recovery_pending` (`pending_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
