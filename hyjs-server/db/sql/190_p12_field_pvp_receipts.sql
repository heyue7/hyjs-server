CREATE TABLE IF NOT EXISTS p12_field_pvp_receipts (
 fight_id VARCHAR(64) NOT NULL PRIMARY KEY,
 player_id BIGINT NOT NULL,
 opponent_id BIGINT NOT NULL,
 stamp BIGINT NULL,
 fight_type INT NOT NULL,
 request_hash VARCHAR(64) NOT NULL,
 policy_hash VARCHAR(64) NOT NULL,
 scope_proof VARCHAR(64) NOT NULL,
 p6_record_id VARCHAR(64) NOT NULL,
 winner_id BIGINT NOT NULL,
 loot_coin BIGINT NOT NULL,
 response LONGBLOB NOT NULL,
 response_hash VARCHAR(64) NOT NULL,
 terminal LONGBLOB NOT NULL,
 terminal_hash VARCHAR(64) NOT NULL,
 replay LONGBLOB NOT NULL,
 replay_hash VARCHAR(64) NOT NULL,
 mv LONGBLOB NOT NULL,
 mv_hash VARCHAR(64) NOT NULL,
 created_at BIGINT NOT NULL,
 busy_until BIGINT NOT NULL,
 UNIQUE KEY p12_pk_stamp(player_id,stamp),
 UNIQUE KEY idx_p12_field_pvp_receipts_p6_record_id(p6_record_id),
 KEY p12_pk_owner(player_id,created_at),
 KEY p12_pk_peer(opponent_id,created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
