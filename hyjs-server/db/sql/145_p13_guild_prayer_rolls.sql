CREATE TABLE IF NOT EXISTS `p13_guild_prayer_rolls` (
 `player_id` bigint NOT NULL,
 `stamp` bigint NOT NULL,
 `guild_id` varchar(64) NOT NULL,
 `day` char(10) NOT NULL,
 `ordinal` bigint NOT NULL,
 `applied_at` bigint NOT NULL,
 `expires_at` bigint NOT NULL,
 `contribution_cost` int NOT NULL,
 `daily_limit` int NOT NULL,
 `duration_hours` int NOT NULL,
 `pool_version` varchar(128) NOT NULL,
 `pool_json` text NOT NULL,
 `pool_hash` char(64) NOT NULL,
 `published_at` bigint NOT NULL,
 `draw` bigint NOT NULL,
 `chosen_index` bigint NOT NULL,
 `effect` blob NOT NULL,
 `effect_hash` char(64) NOT NULL,
 `source` varchar(1024) NOT NULL,
 `source_hash` char(64) NOT NULL,
 PRIMARY KEY (`player_id`,`stamp`),
 UNIQUE KEY `idx_p13_prayer_day_order` (`player_id`,`day`,`ordinal`),
 KEY `idx_p13_prayer_latest` (`player_id`,`applied_at` DESC,`ordinal` DESC,`stamp` DESC)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
