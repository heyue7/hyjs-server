CREATE TABLE IF NOT EXISTS p11_plunder_fight_settlements (
 player_id BIGINT NOT NULL,
 stamp BIGINT NOT NULL,
 opponent_id BIGINT NOT NULL,
 fragment_id VARCHAR(64) NOT NULL,
 request_hash VARCHAR(64) NOT NULL,
 fight_id VARCHAR(64) NOT NULL,
 match_id VARCHAR(64) NOT NULL,
 match_hash VARCHAR(64) NOT NULL,
 p6_record_id VARCHAR(64) NOT NULL,
 scope_proof VARCHAR(64) NOT NULL,
 offer_hash VARCHAR(64) NOT NULL,
 attacker_won BOOLEAN NOT NULL,
 draw BIGINT NOT NULL,
 drop_ppm BIGINT NOT NULL,
 fragment_transferred BOOLEAN NOT NULL,
 energy_spent INT NOT NULL,
 reward_coin INT NOT NULL,
 reward_exp INT NOT NULL,
 response LONGBLOB NOT NULL,
 response_hash VARCHAR(64) NOT NULL,
 terminal LONGBLOB NOT NULL,
 terminal_hash VARCHAR(64) NOT NULL,
 created_at BIGINT NOT NULL,
 PRIMARY KEY (player_id,stamp),
 UNIQUE KEY idx_p11_plunder_fight_settlements_fight_id (fight_id),
 UNIQUE KEY idx_p11_plunder_fight_settlements_match_id (match_id),
 UNIQUE KEY idx_p11_plunder_fight_settlements_p6_record_id (p6_record_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
