CREATE TABLE IF NOT EXISTS p7_section_reward_policies (
 id BIGINT NOT NULL PRIMARY KEY, enabled BOOLEAN NOT NULL DEFAULT FALSE,
 version VARCHAR(64) NOT NULL, source TEXT NOT NULL,
 published_at BIGINT NOT NULL DEFAULT 0,start_at BIGINT NOT NULL DEFAULT 0,end_at BIGINT NOT NULL DEFAULT 0,
 section_from INT NOT NULL DEFAULT 1,section_to INT NOT NULL DEFAULT 3,
 three_reward TEXT NOT NULL,six_reward TEXT NOT NULL,nine_reward TEXT NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
