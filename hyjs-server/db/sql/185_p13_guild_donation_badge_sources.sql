CREATE TABLE IF NOT EXISTS `p13_guild_donation_badge_sources` (
 `player_id` bigint NOT NULL,
 `stamp` bigint NOT NULL,
 `day` varchar(10) NOT NULL,
 `ordinal` bigint NOT NULL,
 `guild_id` varchar(64) NOT NULL,
 `joined_at` bigint NOT NULL,
 `coin_cost` int NOT NULL,
 `badge_amount` int NOT NULL,
 `daily_limit` bigint NOT NULL,
 `version` varchar(128) NOT NULL,
 `source` varchar(1024) NOT NULL,
 `published_at` bigint NOT NULL,
 `created_at` bigint NOT NULL,
 `delivery_id` bigint NOT NULL,
 `delivery_key` varchar(191) NOT NULL,
 `source_hash` char(64) NOT NULL,
 PRIMARY KEY (`player_id`,`stamp`),
 UNIQUE KEY `idx_p13_donation_badge_day` (`player_id`,`day`,`ordinal`),
 UNIQUE KEY `idx_p13_guild_donation_badge_sources_delivery_id` (`delivery_id`),
 UNIQUE KEY `idx_p13_guild_donation_badge_sources_delivery_key` (`delivery_key`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
