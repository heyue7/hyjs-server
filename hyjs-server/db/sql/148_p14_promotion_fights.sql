-- Only a certified computed result may create a point debit and score change.
CREATE TABLE IF NOT EXISTS p14_promotion_fights (
  id CHAR(64) NOT NULL,
  season_index INT NOT NULL,
  server_id BIGINT NOT NULL,
  player_id BIGINT NOT NULL,
  match_index BIGINT NOT NULL,
  stamp BIGINT NOT NULL,
  opponent_server_id BIGINT NOT NULL,
  opponent_id BIGINT NOT NULL,
  attacker_formation_hash CHAR(64) NOT NULL,
  defender_formation_hash CHAR(64) NOT NULL,
  qualification_hash CHAR(64) NOT NULL,
  offer_hash CHAR(64) NOT NULL,
  grant_at BIGINT NOT NULL,
  grant_hash CHAR(64) NOT NULL,
  points_before BIGINT NOT NULL,
  points_after BIGINT NOT NULL,
  score_before BIGINT NOT NULL,
  score_after BIGINT NOT NULL,
  score_delta BIGINT NOT NULL,
  winner_id BIGINT NOT NULL,
  p6_record_id CHAR(64) NOT NULL,
  scope_proof CHAR(64) NOT NULL,
  response LONGBLOB NOT NULL,
  response_hash CHAR(64) NOT NULL,
  terminal LONGBLOB NOT NULL,
  terminal_hash CHAR(64) NOT NULL,
  created_at BIGINT NOT NULL,
  source_hash CHAR(64) NOT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY p14_fight_order (season_index, server_id, player_id, match_index),
  UNIQUE KEY p14_fight_stamp (season_index, server_id, player_id, stamp)
) ENGINE=InnoDB;
