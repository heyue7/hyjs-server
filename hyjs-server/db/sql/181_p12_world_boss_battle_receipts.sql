CREATE TABLE IF NOT EXISTS p12_world_boss_battle_receipts (
  fight_id VARCHAR(64) NOT NULL PRIMARY KEY,
  player_id BIGINT NOT NULL,
  stamp BIGINT NULL,
  instance_id VARCHAR(64) NOT NULL,
  policy_name VARCHAR(96) NOT NULL,
  input_json LONGTEXT NOT NULL,
  input_hash VARCHAR(64) NOT NULL,
  terminal_json LONGTEXT NOT NULL,
  terminal_hash VARCHAR(64) NOT NULL,
  start_proto LONGBLOB NOT NULL,
  start_hash VARCHAR(64) NOT NULL,
  finish_proto LONGBLOB NULL,
  finish_hash VARCHAR(64) NOT NULL,
  predicted_damage BIGINT NOT NULL,
  applied_damage BIGINT NOT NULL DEFAULT 0,
  committed BOOLEAN NOT NULL DEFAULT FALSE,
  finish_hp BIGINT NOT NULL DEFAULT 0,
  created_at BIGINT NOT NULL,
  finished_at BIGINT NOT NULL DEFAULT 0,
  abandoned_at BIGINT NOT NULL DEFAULT 0,
  abandon_reason VARCHAR(64) NOT NULL DEFAULT '',
  UNIQUE KEY p12_boss_stamp (player_id, stamp),
  KEY p12_boss_pending (player_id, committed),
  KEY p12_boss_committed (instance_id, committed),
  KEY idx_p12_world_boss_battle_receipts_instance_id (instance_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
