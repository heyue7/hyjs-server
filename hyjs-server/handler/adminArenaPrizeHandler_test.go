import (
	"context"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"net/http"
	"net/http/httptest"
	"os"
	"path/filepath"
	"strings"
	"testing"
	"time"

	"github.com/gin-gonic/gin"
	"hyjs-server/constUtil"
	"hyjs-server/db"
	"hyjs-server/model"
	"hyjs-server/service"
)

func TestAdminArenaPrizeHTTPAuthCSRFConflictAuditAndTypedPool(t *testing.T) {
	ctx := context.Background()
	dir := t.TempDir()
	if err := db.InitGame(ctx, filepath.Join(dir, "arena-admin.sqlite")); err != nil {
		t.Fatal(err)
	}
	connection, _ := db.GetIns().DB()
	t.Cleanup(func() { connection.Close() })
	boot := filepath.Join(dir, "bootstrap.json")
	if err := os.WriteFile(boot, []byte(`{"username":"prizefixtureadmin","password":"isolated-prize-password-12345"}`), 0600); err != nil {
		t.Fatal(err)
	}
	if err := service.AdminInitialize(ctx, boot); err != nil {
		t.Fatal(err)
	}
	if err := service.InitializeAdminOperations(ctx); err != nil {
		t.Fatal(err)
	}
	prior := gameService
	t.Cleanup(func() { gameService = prior })
	gameService = &service.GameService{}
	if err := gameService.InitializeP11ArenaPrizes(ctx); err != nil {
		t.Fatal(err)
	}
	gin.SetMode(gin.TestMode)
	router := gin.New()
	RegisterAdminRoutes(router, "")
	call := func(method, body, csrf string, cookies []*http.Cookie) *httptest.ResponseRecorder {
		t.Helper()
		r := httptest.NewRequest(method, "/admin/api/arena/prizes", strings.NewReader(body))
		r.Header.Set("Content-Type", "application/json")
		if csrf != "" {
			r.Header.Set("X-CSRF-Token", csrf)
		}
		for _, cookie := range cookies {
			r.AddCookie(cookie)
		}
		w := httptest.NewRecorder()
		router.ServeHTTP(w, r)
		return w
	}
	login := func(username, password string) ([]*http.Cookie, string) {
		t.Helper()
		r := httptest.NewRequest("POST", "/admin/api/auth/login", strings.NewReader(`{"username":"`+username+`","password":"`+password+`"}`))
		r.Header.Set("Content-Type", "application/json")
		w := httptest.NewRecorder()
		router.ServeHTTP(w, r)
		if w.Code != 200 {
			t.Fatal("isolated login", w.Code)
		}
		var result struct {
			Data struct {
				CSRF string `json:"csrfToken"`
			}
		}
		if json.Unmarshal(w.Body.Bytes(), &result) != nil || len(result.Data.CSRF) != 64 {
			t.Fatal("csrf login shape")
		}
		return w.Result().Cookies(), result.Data.CSRF
	}
	read := func(w *httptest.ResponseRecorder) model.AdminArenaPrizeResponse {
		t.Helper()
		if w.Code != 200 {
			t.Fatal("typed arena response", w.Code, w.Body.String())
		}
		var out struct{ Data model.AdminArenaPrizeResponse }
		if json.Unmarshal(w.Body.Bytes(), &out) != nil {
			t.Fatal("typed response JSON")
		}
		return out.Data
	}
	encode := func(req model.AdminArenaPrizeSaveRequest) string { raw, _ := json.Marshal(req); return string(raw) }
	if w := call("GET", "", "", nil); w.Code != 401 {
		t.Fatal("anonymous read", w.Code)
	}
	cookies, csrf := login("prizefixtureadmin", "isolated-prize-password-12345")
	current := read(call("GET", "", "", cookies))
	if current.RegularCoin.Min != 3000 || current.RegularCoin.Max != 6000 || current.OperatorPool.Enabled || len(current.Version) != 64 {
		t.Fatal("persistent initial settings", current)
	}
	req := model.AdminArenaPrizeSaveRequest{Version: current.Version, RegularCoin: model.AdminArenaCoinRange{Min: 9000, Max: 9500}}
	if w := call("PUT", encode(req), "", cookies); w.Code != 403 {
		t.Fatal("missing csrf write", w.Code)
	}
	saved := read(call("PUT", encode(req), csrf, cookies))
	if saved.RegularCoin.Min != 9000 || saved.Version == current.Version || saved.OperatorPool.Enabled {
		t.Fatal("typed range save", saved)
	}
	if w := call("PUT", encode(req), csrf, cookies); w.Code != 409 {
		t.Fatal("stale version", w.Code)
	}
	bad := model.AdminArenaPrizeSaveRequest{Version: saved.Version, RegularCoin: model.AdminArenaCoinRange{Min: 9001, Max: 9000}}
	if w := call("PUT", encode(bad), csrf, cookies); w.Code != 400 {
		t.Fatal("invalid interval", w.Code)
	}
	pool := saved.OperatorPool
	pool.Items = []model.AdminArenaPrizePoolItem{{ResourceID: "coin", Amount: 123, Weight: 1}}
	saved = read(call("PUT", encode(model.AdminArenaPrizeSaveRequest{Version: saved.Version, RegularCoin: saved.RegularCoin, OperatorPool: &pool}), csrf, cookies))
	if saved.OperatorPool.Enabled || len(saved.OperatorPool.Items) != 1 || saved.OperatorPool.Items[0].Amount != 123 {
		t.Fatal("typed disabled pool draft", saved)
	}
	// A valid immutable current-month offer is a finite publication-state fixture;
	// no player battle, item or currency is generated by this HTTP test.
	var stored db.P11ArenaPrizePolicy
	db.GetIns().First(&stored, 1)
	now := time.Now()
	local := now.In(time.FixedZone("UTC+8", 28800))
	end := time.Date(local.Year(), local.Month()+1, 1, 0, 0, 0, 0, local.Location())
	stored.Enabled = true
	stored.PublishedAt = now.Add(-2 * time.Second).UnixMilli()
	stored.StartAt = now.Add(-time.Second).UnixMilli()
	stored.EndAt = end.UnixMilli()
	snapshot, _ := json.Marshal(stored)
	sum := sha256.Sum256(snapshot)
	offer := db.P11ArenaPrizeOffer{Month: local.Format("200601"), Snapshot: string(snapshot), SourceHash: hex.EncodeToString(sum[:]), CapturedAt: now.UnixMilli()}
	if err := db.GetIns().Create(&offer).Error; err != nil {
		t.Fatal(err)
	}
	frozen := read(call("GET", "", "", cookies))
	if !frozen.OperatorPoolFrozen {
		t.Fatal("frozen state missing")
	}
	changed := frozen.OperatorPool
	changed.Items[0].Weight = 2
	if w := call("PUT", encode(model.AdminArenaPrizeSaveRequest{Version: frozen.Version, RegularCoin: model.AdminArenaCoinRange{Min: 1, Max: 1}, OperatorPool: &changed}), csrf, cookies); w.Code != 409 {
		t.Fatal("frozen pool changed", w.Code)
	}
	frozen = read(call("PUT", encode(model.AdminArenaPrizeSaveRequest{Version: frozen.Version, RegularCoin: model.AdminArenaCoinRange{Min: 10000, Max: 10000}}), csrf, cookies))
	if !frozen.OperatorPoolFrozen || frozen.RegularCoin.Min != 10000 {
		t.Fatal("frozen custom pool blocked independent regular range", frozen)
	}
	var token string
	for _, cookie := range cookies {
		if cookie.Name == constUtil.AdminSessionCookieName {
			token = cookie.Value
		}
	}
	actor, err := service.AdminAuthenticate(ctx, token)
	if err != nil {
		t.Fatal(err)
	}
	if _, err = service.AdminCreateUser(ctx, actor, "prizefixtureviewer", "isolated-viewer-password-12345", constUtil.AdminRoleViewer); err != nil {
		t.Fatal(err)
	}
	viewCookies, viewCSRF := login("prizefixtureviewer", "isolated-viewer-password-12345")
	if w := call("GET", "", "", viewCookies); w.Code != 200 {
		t.Fatal("viewer cannot read", w.Code)
	}
	if w := call("PUT", encode(model.AdminArenaPrizeSaveRequest{Version: frozen.Version, RegularCoin: frozen.RegularCoin}), viewCSRF, viewCookies); w.Code != 403 {
		t.Fatal("viewer wrote settings", w.Code)
	}
	var audits int64
	db.GetIns().Model(&db.AdminAudit{}).Where("action=?", constUtil.AdminArenaPrizeAuditAction).Count(&audits)
	if audits != 3 {
		t.Fatal("successful saves not audited once", audits)
	}
	// Calendar offsets belong to the whole server. HTTP admin contexts have no
	// character binding and must still report the shifted offer month.
	if err := gameService.InitializeServerGameClock(ctx); err != nil {
		t.Fatal(err)
	}
	if err := db.GetIns().Model(&db.ServerGameClock{}).Where("server_id=?", 1).Updates(map[string]any{"offset_days": int64(40), "high_days": int64(40), "revision": int64(1)}).Error; err != nil {
		t.Fatal(err)
	}
	shifted := read(call("GET", "", "", cookies))
	if shifted.OperatorPoolFrozen {
		t.Fatal("admin freeze ignored global server month")
	}
	t.Log("actual admin router: anonymous401, csrf403, viewer403/read200, stale409, invalid400, typed disabled pool save, frozen409, independent regular range save, audit3")
}
